import json, re, sys, shutil, datetime

CAT, LG = sys.argv[1], sys.argv[2]
cat = json.load(open(CAT, encoding='utf-8'))
lg = json.load(open(LG, encoding='utf-8'))
bak = LG + '.bak-' + datetime.date.today().strftime('%Y%m%d')
shutil.copy(LG, bak)
print('backup ->', bak)


def norm_date(d):
    m = re.search(r'(?:中華民國|民國)\s*(\d+)\s*年\s*(\d+)\s*月\s*(\d+)\s*日', d)
    s = f"{int(m.group(1))}.{int(m.group(2))}.{int(m.group(3))}" if m else d
    n = re.search(r'((?:府|北府|新北府|高市府)\S*?字第\s*\d+\s*號?)', d)
    return s + (f"（{n.group(1).replace(' ', '')}）" if n else '')


def _n(t):
    return re.sub(r'[（）()\s]', '', t)


def D(county, sub, system=None):
    hits = [d for d in cat if d['county'] == county and _n(sub) in _n(d['title']) and (system is None or d['system'] == system)]
    if not hits:
        raise SystemExit(f'找不到 {county} {sub} {system}')
    if len(hits) > 1:
        hits.sort(key=lambda x: x['date'], reverse=True)
    return hits[0]


def entry(doc, summary, note=None, status='現行'):
    e = {
        'title': doc['title'].replace('廢/停 ', ''),
        'year': norm_date(doc['date']) + ('（已廢止／停止適用）' if doc['title'].startswith('廢/停') else ''),
        'url': doc['source'],
        'accessible': 'yes',
        'summary': summary,
        'points': doc['points'],
        'local_path': doc['local_path'],
        'source_system': doc['system'],
        'fetched': '2026-10-31',
        'n_points': doc['n_points'],
    }
    if note:
        e['note'] = note
    if doc.get('note'):
        e['history'] = doc['note']
    return e


def apply(county, plan):
    g = next(x for x in lg['local_governments'] if x['name'] == county)
    regs = g['regulations']
    for match, (sub, system), summary, note in plan:
        doc = D(county, sub, system)
        e = entry(doc, summary, note)
        idx = None
        if match:
            for i, r in enumerate(regs):
                if match in r['title']:
                    idx = i
                    break
        if idx is None:
            regs.append(e)
        else:
            old = regs[idx]
            if old['url'] != e['url']:
                e['url_prev'] = old['url']
            if old['title'] != e['title']:
                e['title_prev'] = old['title']
            regs[idx] = e
    return g


def fields(county, **kw):
    g = next(x for x in lg['local_governments'] if x['name'] == county)
    for k, v in kw.items():
        if k in ('notable_practices', 'sources', 'contract_types'):
            for item in v:
                if item not in g[k]:
                    g[k].append(item)
        else:
            g[k] = v


